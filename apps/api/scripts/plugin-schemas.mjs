// The plugins' generated table definitions (docs/PLUGINS.md, "Database changes"). A plugin either
// lists its tables in public (package.json `apensum.tables`) or owns a whole Postgres schema
// (`apensum.dbSchema`); the core's introspection leaves them out (drizzle.config.ts) and each plugin
// gets its own `api/db/schema.ts`, introspected from the same database with only its tables. drizzle-kit writes every enum of the database and refers to the
// core's tables (users, projects, ...) without importing them, so the file is finished here: the
// enums it does not use are dropped, and the core's tables and enums it uses are imported from
// `@worktime3/api/schema`. Used by introspect.mjs and check-schema.mjs.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const apiDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const pluginsDir = process.env.APENSUM_PLUGINS_DIR?.trim() ? resolve(process.env.APENSUM_PLUGINS_DIR.trim()) : join(apiDir, '../../plugins');
const shell = process.platform === 'win32';

/** Plugins that own tables: id, folder, tables in public or their own schema, and their generated schema's path. */
export function pluginsWithTables() {
  if (!existsSync(pluginsDir)) return [];
  return readdirSync(pluginsDir)
    .map((id) => ({ id, dir: join(pluginsDir, id) }))
    .filter((p) => existsSync(join(p.dir, 'package.json')))
    .map((p) => {
      const manifest = JSON.parse(readFileSync(join(p.dir, 'package.json'), 'utf8')).apensum ?? {};
      return { ...p, tables: Array.isArray(manifest.tables) ? manifest.tables : [], dbSchema: typeof manifest.dbSchema === 'string' ? manifest.dbSchema : null };
    })
    .filter((p) => p.tables.length > 0 || p.dbSchema)
    .map((p) => ({ ...p, schema: join(p.dir, 'api', 'db', 'schema.ts') }))
    .sort((a, b) => a.id.localeCompare(b.id));
}

/** Introspects one plugin's tables and returns its finished schema.ts source. */
export function introspectPlugin(plugin) {
  const out = join(apiDir, `.drizzle-introspect-${plugin.id}`);
  const config = join(apiDir, `.drizzle-${plugin.id}.config.ts`);
  rmSync(out, { recursive: true, force: true });
  writeFileSync(
    config,
    `import { defineConfig } from 'drizzle-kit';
export default defineConfig({
  dialect: 'postgresql',
  out: ${JSON.stringify(out)},
  dbCredentials: { url: process.env.DATABASE_URL ?? 'postgresql://worktime:worktime_dev_only@localhost:5431/worktime' },
  introspect: { casing: 'preserve' },
  ${plugin.dbSchema ? `schemaFilter: [${JSON.stringify(plugin.dbSchema)}],` : `schemaFilter: ['public'],
  tablesFilter: ${JSON.stringify(plugin.tables)},`}
});
`,
  );
  try {
    execFileSync('npx', ['drizzle-kit', 'introspect', '--config', config], { cwd: apiDir, stdio: ['ignore', 'ignore', 'inherit'], shell });
    const raw = join(out, 'schema.ts');
    if (!existsSync(raw)) throw new Error(`drizzle-kit wrote no schema.ts for plugin ${plugin.id}`);
    execFileSync('node', [join(apiDir, 'scripts', 'fix-introspected-schema.mjs'), raw], { stdio: 'ignore' });
    return finishPluginSchema(plugin, readFileSync(raw, 'utf8'));
  } finally {
    rmSync(out, { recursive: true, force: true });
    rmSync(config, { force: true });
  }
}

/** Drops unused enums and imports the core's tables and enums the plugin's tables refer to. */
export function finishPluginSchema(plugin, src) {
  const lines = src.replace(/\r\n/g, '\n').split('\n');
  const enumLine = /^export const (\w+) = pgEnum\(/;
  const enums = lines.map((l) => enumLine.exec(l)?.[1]).filter(Boolean);
  let body = lines.filter((l) => !enumLine.test(l)).join('\n');
  // Tables in public (`pgTable(`) or in the plugin's own schema (`<schema>.table(`).
  const own = new Set([...body.matchAll(/^export const (\w+) = (?:pgTable|\w+\.table)\(/gm)].map((m) => m[1]));
  const usedEnums = enums.filter((e) => new RegExp(`\\b${e}\\(`).test(body));
  const coreTables = [...new Set([...body.matchAll(/foreignColumns: \[(\w+)\.\w+/g)].map((m) => m[1]))].filter((t) => !own.has(t)).sort();
  const core = [...usedEnums, ...coreTables].sort();
  body = body.replace(/\bpgEnum, |, pgEnum\b/, '').replace(/\n{3,}/g, '\n\n');
  const header = `// GENERATED by \`npm run dev:introspect\` (apps/api/scripts/plugin-schemas.mjs) from the database:
// the tables of plugin "${plugin.id}" (package.json ${plugin.dbSchema ? `apensum.dbSchema "${plugin.dbSchema}"` : 'apensum.tables'}). Never edit by hand.
`;
  const importCore = core.length ? `import { ${core.join(', ')} } from '@worktime3/api/schema';\n` : '';
  return header + body.replace(/(import \{ sql \} from "drizzle-orm"\n)/, `$1${importCore}`);
}
